const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(10000);
  const errors=[];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.SRE_TEST_URL || 'http://127.0.0.1:8080');
  await page.getByRole('heading',{name:'Memory pressure detected',exact:false}).waitFor();
  await page.screenshot({path:'.ai-sre/dashboard-desktop.png',fullPage:true});
  await page.locator('[data-evidence="E1"]').click();
  assert.equal(await page.locator('#evidence-E1').getAttribute('open'),'');
  await page.locator('#integrations-nav').click();
  await page.getByRole('heading',{name:'Your evidence sources.'}).waitFor();
  assert.equal(await page.locator('.connection-card').count(),5);
  await page.locator('#incidents-nav').click();
  await page.getByRole('button',{name:'New investigation'}).click();
  await page.locator('[name=service]').fill('checkout-api');
  await page.locator('[name=title]').fill('Browser smoke: investigate checkout errors');
  await page.getByRole('button',{name:'Create & investigate'}).click();
  await page.locator('.detail-header h2').filter({hasText:'Browser smoke'}).waitFor();
  await page.getByRole('heading',{name:'Memory pressure detected',exact:false}).waitFor();
  await page.locator('#followup-input').fill('Check the dependency evidence again');
  await page.locator('#followup-form button').click();
  await page.getByRole('button',{name:'Evidence (8)',exact:true}).waitFor();
  await page.getByRole('button',{name:'Trace',exact:true}).click();
  await page.locator('.event strong').filter({hasText:'run completed'}).first().waitFor();
  assert.ok(await page.locator('.event small').filter({hasText:'Run '}).count() > 0);
  await page.getByRole('button',{name:'Mark resolved',exact:false}).click();
  await page.locator('.detail-meta .badge.resolved').waitFor();
  await page.locator('#search').fill('does-not-exist');
  await page.getByText('No investigations found.').waitFor();
  await page.locator('#search').fill('');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.screenshot({path:'.ai-sre/dashboard-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: dashboard, evidence citations, connections, create, follow-up, runtime trace, resolve, search, mobile layout; no browser exceptions');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
